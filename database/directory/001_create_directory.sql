-- REVIEW before applying manually to a non-production database.
-- Only creates objects in the dedicated directory schema.
BEGIN;
CREATE SCHEMA IF NOT EXISTS directory;
CREATE TABLE IF NOT EXISTS directory.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug varchar(120) NOT NULL UNIQUE,
    name varchar(120) NOT NULL
);
CREATE TABLE IF NOT EXISTS directory.businesses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug varchar(180) NOT NULL UNIQUE,
    name varchar(180) NOT NULL,
    description text,
    category_id integer NOT NULL REFERENCES directory.categories(id) ON DELETE RESTRICT,
    district varchar(80) NOT NULL,
    address text,
    phone varchar(40),
    whatsapp varchar(40),
    website varchar(500),
    image_url varchar(500),
    status varchar(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Published', 'Rejected', 'Suspended')),
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_directory_business_status_district
    ON directory.businesses(status, district);
COMMIT;
