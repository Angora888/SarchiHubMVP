BEGIN;
CREATE TABLE IF NOT EXISTS directory.admin_accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(254) NOT NULL UNIQUE,
  password_hash text NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS directory.moderation_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id integer NOT NULL REFERENCES directory.businesses(id) ON DELETE RESTRICT,
  admin_id integer NOT NULL REFERENCES directory.admin_accounts(id) ON DELETE RESTRICT,
  previous_status varchar(20) NOT NULL,
  new_status varchar(20) NOT NULL,
  reason varchar(500),
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMIT;
-- No default administrators or credentials are seeded here.
-- Provision account explicitly with a securely produced BCrypt hash in a protected process.
